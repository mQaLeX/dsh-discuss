/**
 * Renderer for the two bundles' patch layers.
 *
 * Each bundle inserts:
 * - a Host plugin row: process-wide store/relay/web route (discuss) or the
 *   admin tools (discuss-admin);
 * - an agent preset carrying the standard tool set, used as the per-session
 *   mode marker. The Host plugin gates itself by that preset id.
 *
 * DSH presets are flat declarations (no `extends`), so the standard plugin list
 * is copied verbatim; test/presets.test.js fails when the installed standard
 * preset drifts.
 */

const PERSONA = '              prefix: You are a coding agent powered by the {{model}} model.'
const SKILL_REQUIRE = "createRequire(process.argv[1] ?? process.cwd())"

const HEADER = [
  `# Generated by client/scripts/build-presets.mjs from the DSH standard preset.`,
  `# Re-run after a DSH upgrade instead of editing the plugin list by hand.`,
  '',
].join('\n')

/**
 * @param {string} standardText contents of the installed standard.patch.yml
 * @returns {{ discuss: string, admin: string }}
 */
export function renderPresets(standardText) {
  const lines = standardText.split('\n')
  const start = lines.findIndex(line => line === '        plugins:')
  if (start < 0) throw new Error('standard preset: no "        plugins:" line')
  const block = lines.slice(start + 1).join('\n').replace(/\s+$/, '')

  if (!block.includes(PERSONA)) throw new Error('standard preset: persona prefix changed; update client/scripts/preset-template.mjs')
  if (!block.includes('createRequire(baseUrl)')) throw new Error('standard preset: skill require changed; update client/scripts/preset-template.mjs')

  const standardPlugins = block.replace('createRequire(baseUrl)', SKILL_REQUIRE)

  /**
   * @param {{ hostId: string, plugin: string, presetId: string, label: string, description: string, order: number, persona: string }} spec
   * @returns {string}
   */
  function bundle(spec) {
    const plugins = standardPlugins.replace(PERSONA, `              prefix: ${spec.persona}`)
    return [
      `    - id: ${spec.hostId}`,
      `      name: '${spec.plugin}'`,
      `      config: {}`,
      `    - id: preset-${spec.presetId}`,
      `      name: '@deepseek-ai/dsh-agent-preset'`,
      `      config:`,
      `        id: ${spec.presetId}`,
      `        name: ${spec.label}`,
      `        description: ${spec.description}`,
      `        order: ${spec.order}`,
      `        plugins:`,
      plugins,
    ].join('\n')
  }

  const discuss = bundle({
    hostId: 'dsh-discuss',
    plugin: '@local/dsh-discuss',
    presetId: 'discuss',
    label: 'Discuss',
    description: 'Participates in the LAN discussion board.',
    order: 10,
    persona: 'You are a coding agent that also participates in the LAN discussion board.',
  })
  const admin = bundle({
    hostId: 'dsh-discuss-admin',
    plugin: '@local/dsh-discuss-admin',
    presetId: 'discuss-admin',
    label: 'Discuss Admin',
    description: 'Creates discussion topics for other agents.',
    order: 11,
    persona: 'You administer the LAN discussion board. Create topics for other agents; do not participate in discussions.',
  })
  return {
    discuss: `${HEADER}- insert:\n${discuss}\n`,
    admin: `${HEADER}- insert:\n${admin}\n`,
  }
}
